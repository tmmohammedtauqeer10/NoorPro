// Builds src/kb_data.js from kb/*.json, with gemini-embedding-001 vectors (256-d, normalised) for retrieval.
// Run: node kb/build.mjs   (needs GEMINI_API_KEY in the environment; the key is never written anywhere)
import fs from "fs";
const DIM = 256;
const entries = [];
for (const f of ["aqeedah_tasawwuf.json", "fiqh_compare.json"]) {
  for (const e of JSON.parse(fs.readFileSync(new URL(f, import.meta.url)))) entries.push({ ...e, school: e.positions ? "compare" : (e.school || "all") });
}
export function docText(e) {
  const pos = e.positions ? Object.entries(e.positions).map(([k, v]) => `${k}: ${v}`).join("\n") : "";
  return [e.topic, (e.tags || []).join(", "), e.text || e.common || "", pos].filter(Boolean).join("\n");
}
async function embed(texts) {
  const r = await fetch("https://generativelanguage.googleapis.com/v1beta/models/gemini-embedding-001:batchEmbedContents", {
    method: "POST", headers: { "content-type": "application/json", "x-goog-api-key": process.env.GEMINI_API_KEY },
    body: JSON.stringify({ requests: texts.map((t) => ({ model: "models/gemini-embedding-001", content: { parts: [{ text: t }] }, taskType: "RETRIEVAL_DOCUMENT", outputDimensionality: DIM })) }),
  });
  if (!r.ok) throw new Error("embed status " + r.status);
  return (await r.json()).embeddings.map((e) => e.values);
}
const vecs = await embed(entries.map(docText));
const toB64 = (v) => { const n = Math.hypot(...v); return Buffer.from(new Float32Array(v.map((x) => x / n)).buffer).toString("base64"); };
const out = entries.map((e, i) => ({ ...e, v: toB64(vecs[i]) }));
fs.writeFileSync(new URL("../src/kb_data.js", import.meta.url),
  `// Generated by kb/build.mjs from kb/*.json - original summaries with classical citations. Do not edit by hand.\nexport const KB_DIM = ${DIM};\nexport const KB = ${JSON.stringify(out)};\n`);
console.log("entries", out.length);
