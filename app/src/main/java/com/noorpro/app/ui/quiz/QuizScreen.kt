private data class QuizRun(
    val title: String,
    val cat: QuizCat?,
    val daily: Boolean,
    val questions: List<QuizQuestion2>,
    val index: Int = 0,
    val picked: Int? = null,
    val score: Int = 0,
    val xp: Int = 0,
    val wrong: List<QuizQuestion2> = emptyList(),
    val replay: () -> QuizRun? = { null },
)

private fun online(ctx: Context): Boolean = runCatching {
    val cm = ctx.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
    cm.getNetworkCapabilities(cm.activeNetwork)?.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET) == true
}.getOrDefault(false)

/** 1.2.0 (115) quiz: home → play → result, all offline except translation and Noor AI questions. */
@Composable
fun QuizScreen(viewModel: DeenViewModel) {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    val store = remember { QuizStore(ctx) }
    val bank = remember { QuizBank.load(ctx) }
    var generated by remember { mutableStateOf(store.generated) }
    val all = remember(bank, generated) { bank + generated }
    val kids = remember { runCatching { KidsMode.enforced }.getOrDefault(false) }
    val appLang by viewModel.appLanguage.collectAsState()
    var lang by remember {
        mutableStateOf(QuizStrings.norm(store.lang ?: runCatching { NoorAiChatStore.language(ctx) }.getOrNull()?.takeIf { it != "auto" }
            ?: when (appLang) { AppLanguage.AR -> "ar"; AppLanguage.UR -> "ur"; else -> "en" }))
    }
    var madhhab by remember { mutableStateOf(if (store.hasMadhhab) store.madhhab else QuizMadhhab.norm(runCatching { NoorAiChatStore.madhhab(ctx) }.getOrNull())) }
    var level by remember { mutableStateOf(store.level) }
    var timer by remember { mutableStateOf(store.timer) }
    var aiCat by remember { mutableStateOf(QuizCat.SEERAH) }
    var aiBusy by remember { mutableStateOf(false) }
    var aiNote by remember { mutableStateOf<String?>(null) }
    var tick by remember { mutableIntStateOf(0) } // refreshes stats after a run
    var run by remember { mutableStateOf<QuizRun?>(null) }
    var result by remember { mutableStateOf<QuizResultUi?>(null) }
    var resultReplay by remember { mutableStateOf<(() -> QuizRun?)?>(null) }
    var timeLeft by remember { mutableStateOf<Int?>(null) }
    var translating by remember { mutableStateOf(false) }
    var untranslated by remember { mutableStateOf(false) }

    fun t(k: String) = QuizStrings.s(k, lang)

    fun categoryRun(c: QuizCat): QuizRun? {
        val qs = QuizEngine.session(all, c, if (c == QuizCat.KIDS) null else level, System.nanoTime(), avoid = store.seen)
        return if (qs.isEmpty()) null else QuizRun(QuizStrings.cat(c, lang), c, false, qs, replay = { categoryRun(c) })
    }
    fun dailyRun(): QuizRun? {
        val qs = QuizEngine.daily(bank, QuizEngine.dayKey(), kids)
        return if (qs.isEmpty()) null else QuizRun(t("daily"), null, true, qs, replay = { dailyRun() })
    }
    fun reviewRun(): QuizRun? {
        val ids = store.mistakes
        val qs = all.filter { it.id in ids }.shuffled().take(QuizEngine.SESSION_SIZE)
        return if (qs.isEmpty()) null else QuizRun(t("review"), null, false, qs, replay = { reviewRun() })
    }

    fun pick(i: Int) {
        val r = run ?: return
        if (r.picked != null) return
        val q = r.questions[r.index]
        val ok = i == q.answerFor(madhhab)
        val gain = QuizEngine.xpFor(q.level, ok, fast = timer && (timeLeft ?: 0) >= 20)
        store.recordAnswer(q, ok, gain)
        if (gain > 0) viewModel.addQuizPoints(gain)
        run = r.copy(picked = i, score = r.score + if (ok) 1 else 0, xp = r.xp + gain, wrong = if (ok) r.wrong else r.wrong + q)
    }

    fun finish(r: QuizRun) {
        var streak: Int? = null
        var xp = r.xp
        if (r.daily) {
            val first = store.lastDaily != QuizEngine.dayKey()
            streak = store.finishDaily(r.score, 20)
            if (first) { xp += 20; viewModel.addQuizPoints(20) }
        } else store.finishCategory(r.cat, r.score)
        result = QuizResultUi(r.title, r.score, r.questions.size, xp, lang, madhhab, streak, r.wrong)
        resultReplay = r.replay
        run = null
        tick++
    }

    // Timer
    val cur = run
    LaunchedEffect(cur?.index, cur?.picked == null, timer, cur != null) {
        if (cur == null || !timer) { timeLeft = null; return@LaunchedEffect }
        if (cur.picked != null) return@LaunchedEffect
        timeLeft = QuizEngine.TIMER_SECONDS
        while ((timeLeft ?: 0) > 0) { delay(1000); timeLeft = (timeLeft ?: 1) - 1 }
        pick(-1)
    }

    // On-demand translation of the current (and next) question, cached per language and madhhab.
    LaunchedEffect(cur?.index, cur?.questions?.size, lang, madhhab) {
        untranslated = false
        val r = run ?: return@LaunchedEffect
        if (lang == "en") return@LaunchedEffect
        for (idx in listOf(r.index, r.index + 1)) {
            val q = run?.questions?.getOrNull(idx) ?: continue
            // 1.2.0 (116): Deenflow questions ship native Urdu/Hindi/Arabic text; no AI call needed.
            if (q.isTranslated(lang) && q.explanation[lang] != null) continue
            val key = if (q.hasMadhhabVariants) "${q.id}_$madhhab" else q.id
            val cached = store.translation(lang, key)
            val tr = cached ?: if (online(ctx)) {
                if (idx == r.index) translating = true
                QuizAi.translate(q, lang, madhhab)?.also { store.saveTranslation(lang, key, it) }
            } else null
            if (idx == r.index) translating = false
            if (tr != null) {
                val now = run ?: return@LaunchedEffect
                run = now.copy(questions = now.questions.toMutableList().also { it[idx] = QuizAi.applyTranslation(q, lang, madhhab, tr) })
            } else if (idx == r.index) untranslated = true
        }
    }

    BackHandler(enabled = run != null || result != null) { run = null; result = null; tick++ }

    val r = run
    val res = result
    when {
        r != null -> QuizPlayContent(
            QuizPlayUi(r.title, r.questions[r.index], r.index, r.questions.size, lang, madhhab, r.picked, if (timer) timeLeft else null, r.score,
                translating, untranslated && !r.questions[r.index].isTranslated(lang)),
            QuizPlayActions(
                onPick = ::pick,
                onNext = { if (r.index + 1 >= r.questions.size) finish(r) else run = r.copy(index = r.index + 1, picked = null) },
                onQuit = { run = null; tick++ },
            ),
        )
        res != null -> QuizResultContent(res, QuizResultActions(
            onReview = { result = null; run = reviewRun() },
            onAgain = { result = null; run = resultReplay?.invoke() },
            onDone = { result = null; tick++ },
        ))
        else -> {
            val home = remember(tick, lang, madhhab, level, timer, generated, aiBusy, aiNote, aiCat) {
                QuizHomeUi(
                    lang = lang, madhhab = madhhab, streak = store.streak, xp = store.xp,
                    accuracy = store.answered.takeIf { it > 0 }?.let { store.correct * 100 / it },
                    dailyScore = store.lastDailyScore, mistakes = store.mistakes.count { id -> all.any { it.id == id } },
                    counts = all.groupingBy { it.cat }.eachCount(), best = QuizCat.entries.mapNotNull { c -> store.best(c)?.let { c to it } }.toMap(),
                    level = level, timer = timer, kids = kids, aiCat = aiCat, aiBusy = aiBusy, aiNote = aiNote, aiCount = generated.size,
                )
            }
            QuizHomeContent(home, QuizHomeActions(
                onBack = { if (!viewModel.goBack()) viewModel.navigateTo(DeenScreen.DASHBOARD) },
                onDaily = { run = dailyRun() },
                onCategory = { c -> run = categoryRun(c) },
                onReview = { run = reviewRun() },
                onLevel = { level = it; store.level = it },
                onTimer = { timer = it; store.timer = it },
                onMadhhab = { madhhab = it; store.madhhab = it },
                onLang = { lang = it; store.lang = it },
                onAiCat = { aiCat = it },
                onGenerate = {
                    if (!online(ctx)) aiNote = t("ai_offline") else scope.launch {
                        aiBusy = true; aiNote = null
                        val made = runCatching { QuizAi.generate(aiCat, madhhab, level) }.getOrDefault(emptyList())
                        val fresh = made.filter { m -> all.none { it.id == m.id } }
                        if (fresh.isNotEmpty()) { generated = generated + fresh; store.generated = generated }
                        aiNote = if (fresh.isEmpty()) t("ai_none") else "${fresh.size} ${t("ai_added")} · ${QuizStrings.cat(aiCat, lang)}"
                        aiBusy = false
                    }
                },
            ))
        }
    }
}
